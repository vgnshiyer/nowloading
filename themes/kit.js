// nowloading drawing kit: plain helpers every theme draws with. Pure functions, no engine access,
// so the mod, the browser demo and the frame builder all share them.
const f = n => +(+n).toFixed(2)
const svg = (w, body, h = 20) => `<svg xmlns="http://www.w3.org/2000/svg" width="${f(w)}" height="${h}" viewBox="0 0 ${f(w)} ${h}">${body}</svg>`
let uid = 0
const id = name => `${name}${++uid}`

function bitmap(rows, x, y, p) {
  let d = ''
  rows.forEach((row, ry) => {
    let run = -1
    for (let i = 0; i <= row.length; i++) {
      if (row[i] === '1' && run < 0) run = i
      if (row[i] !== '1' && run >= 0) {
        d += `M${f(x + run * p)} ${f(y + ry * p)}h${f((i - run) * p)}v${f(p)}h${f(-(i - run) * p)}z`
        run = -1
      }
    }
  })
  return d
}

