const osdWidth = text => [...text].reduce((w, ch) => w + OSD[ch][0].length + 1, -1)
function osd(text, x, y, p) {
  let d = '', cx = 0
  for (const ch of text) { d += bitmap(OSD[ch], x + cx * p, y, p); cx += OSD[ch][0].length + 1 }
  return d
}

// Seven-segment digit
const SEGMENTS = { 0: 'abcdef', 1: 'bc', 2: 'abged', 3: 'abgcd', 4: 'fgbc', 5: 'afgcd', 6: 'afgedc', 7: 'abc', 8: 'abcdefg', 9: 'abcdfg', ' ': '' }
function seven(ch, x, y, w, h, t, on, off) {
  const half = h / 2, lit = SEGMENTS[ch] ?? ''
  const r = {
    a: [x + t * .65, y, w - t * 1.3, t], d: [x + t * .65, y + h - t, w - t * 1.3, t], g: [x + t * .65, y + half - t / 2, w - t * 1.3, t],
    f: [x, y + t * .6, t, half - t * .85], b: [x + w - t, y + t * .6, t, half - t * .85],
    e: [x, y + half + t * .25, t, half - t * .85], c: [x + w - t, y + half + t * .25, t, half - t * .85],
  }
  return Object.entries(r).map(([k, [rx, ry, rw, rh]]) =>
    `<rect x="${f(rx)}" y="${f(ry)}" width="${f(rw)}" height="${f(rh)}" rx="${f(t / 3)}" fill="${lit.includes(k) ? on : off}"/>`).join('')
}

const tape = sec => { const s = Math.floor(sec); return `${Math.floor(s / 3600)}:${String(Math.floor(s / 60) % 60).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}` }
const nativeTime = sec => { const s = Math.floor(sec); return s < 60 ? `${s}s` : `${Math.floor(s / 60)}m ${s % 60}s` }

